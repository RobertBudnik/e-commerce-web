-- =============================================================================
-- Kolejka zadań w tle (wzorzec Outbox)
--
-- Problem, który to rozwiązuje. Potwierdzenie zamówienia wysyła dziś webhook
-- Stripe'a, w środku obsługi żądania. To działa dopóki wszystko działa —
-- i przestaje w dokładnie tym momencie, w którym najbardziej boli:
--
--   • funkcja brzegowa padnie po `mark_order_paid`, a przed wysyłką
--     → zamówienie jest opłacone, klient nie dostaje niczego
--   • Resend jest chwilowo niedostępny
--     → jedna próba, brak ponowienia, mail przepada
--   • wysyłka trwa 4 sekundy
--     → Stripe czeka, a przy przekroczeniu limitu uzna webhooka za nieudany
--       i przyśle go ponownie
--
-- Wzorzec Outbox odwraca zależność: zapis stanu i zakolejkowanie roboty
-- dzieją się w **jednej transakcji**, w bazie. Skoro zamówienie jest
-- opłacone, to zadanie na pewno istnieje — nie ma okna, w którym jedno
-- jest prawdą, a drugie nie. Wykonaniem zajmuje się osobny proces, który
-- może próbować tyle razy, ile trzeba, i którego awaria niczego nie cofa.
--
-- Dlaczego tabela, a nie SQS/Pub-Sub: dokładanie usługi kolejkowej do stosu,
-- który ma jedną bazę i kilkanaście zamówień dziennie, to koszt bez zysku.
-- Postgres z `FOR UPDATE SKIP LOCKED` jest poprawną kolejką do znacznie
-- większej skali niż ta. Moment na Kafkę poznamy po tym, że ta tabela zacznie
-- puchnąć — a nie po tym, że tak się robi.
-- =============================================================================

do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
  else
    raise notice 'pg_cron niedostępne — kolejkę trzeba będzie drenować z zewnątrz.';
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Tabela zadań
-- ---------------------------------------------------------------------------
create table if not exists public.zadania (
  id bigint generated by default as identity primary key,

  rodzaj text not null check (rodzaj in (
    'potwierdzenie_zamowienia',
    'przypomnienie_koszyk'
  )),

  -- Klucz naturalny zadania, np. 'potwierdzenie:<uuid zamówienia>'.
  -- Unikalny, więc dwa wywołania wyzwalacza dla tego samego zamówienia
  -- dodadzą jeden wiersz. To jest pierwsza z dwóch warstw idempotencji:
  -- ta pilnuje, żeby nie powstało drugie ZADANIE.
  klucz text not null unique,

  ladunek jsonb not null default '{}'::jsonb,

  stan text not null default 'oczekuje'
    check (stan in ('oczekuje', 'w_toku', 'zrobione', 'porazka')),

  proby integer not null default 0,
  -- Kiedy najwcześniej wolno spróbować. Przy porażce odsuwane wykładniczo.
  nastepna_proba timestamptz not null default now(),
  ostatni_blad text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.zadania is
  'Outbox: robota w tle zakolejkowana w tej samej transakcji, co zmiana stanu.';
comment on column public.zadania.klucz is
  'Klucz naturalny. Unikalny — dwa wyzwolenia dla tego samego zdarzenia dają jedno zadanie.';
comment on column public.zadania.stan is
  'porazka = wyczerpane próby. To jest martwa litera (DLQ) — do obejrzenia ręcznie.';

-- Zapytanie drenujące brzmi zawsze „co jest do wzięcia i już dojrzało",
-- więc indeks idzie dokładnie w tej kolejności. Częściowy, bo zadania
-- zrobione stanowią z czasem 99% tabeli i nie ma powodu ich indeksować.
create index if not exists zadania_do_wziecia
  on public.zadania (nastepna_proba)
  where stan in ('oczekuje', 'w_toku');

alter table public.zadania enable row level security;
-- Bez polityk: tabela jest wewnętrzna. Sięga do niej wyłącznie funkcja
-- uruchamiana z prawami właściciela i klucz service_role.

-- ---------------------------------------------------------------------------
-- Dodanie zadania
-- ---------------------------------------------------------------------------
create or replace function public.dodaj_zadanie(
  p_rodzaj text,
  p_klucz text,
  p_ladunek jsonb default '{}'::jsonb
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.zadania (rodzaj, klucz, ladunek)
  values (p_rodzaj, p_klucz, p_ladunek)
  on conflict (klucz) do nothing;
$$;

revoke all on function public.dodaj_zadanie(text, text, jsonb) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Pobranie porcji do wykonania
-- ---------------------------------------------------------------------------
-- `for update skip locked` to sedno: dwa równoległe procesy drenujące wezmą
-- **rozłączne** porcje, zamiast bić się o te same wiersze. Bez tego kolejka
-- działa wyłącznie przy jednym pracowniku.
--
-- Zadania `w_toku`, których `nastepna_proba` już minęła, wracają do puli —
-- to sprzątanie po pracowniku, który padł w połowie roboty i nigdy nie
-- oznaczył wyniku.
create or replace function public.wez_zadania(p_ile integer default 10)
returns setof public.zadania
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with wybrane as (
    select z.id
    from public.zadania z
    where z.stan in ('oczekuje', 'w_toku')
      and z.nastepna_proba <= now()
    order by z.nastepna_proba
    limit greatest(p_ile, 0)
    for update skip locked
  )
  update public.zadania z
  set stan = 'w_toku',
      proby = z.proby + 1,
      -- Widełki na wypadek padnięcia pracownika: jeśli za pięć minut nikt
      -- nie oznaczył wyniku, zadanie wróci do puli.
      nastepna_proba = now() + interval '5 minutes',
      updated_at = now()
  from wybrane w
  where z.id = w.id
  returning z.*;
end;
$$;

revoke all on function public.wez_zadania(integer) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Oznaczenie wyniku
-- ---------------------------------------------------------------------------
create or replace function public.zamknij_zadanie(
  p_id bigint,
  p_udalo boolean,
  p_blad text default null,
  p_max_prob integer default 5
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_udalo then
    update public.zadania
    set stan = 'zrobione', ostatni_blad = null, updated_at = now()
    where id = p_id;
    return;
  end if;

  update public.zadania
  set
    -- Po wyczerpaniu prób zadanie ląduje w martwej literze zamiast kręcić
    -- się w kółko. Ktoś ma je zobaczyć, a nie ono ma się samo naprawiać.
    stan = case when proby >= p_max_prob then 'porazka' else 'oczekuje' end,
    -- Odsuwanie wykładnicze: 1, 2, 4, 8, 16 minut. Dostawca poczty, który
    -- właśnie leży, nie wstanie szybciej dlatego, że pytamy co sekundę.
    nastepna_proba = now() + (power(2, least(proby, 6)) * interval '1 minute'),
    ostatni_blad = p_blad,
    updated_at = now()
  where id = p_id;
end;
$$;

revoke all on function public.zamknij_zadanie(bigint, boolean, text, integer) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Wyzwalacz: opłacone zamówienie kolejkuje potwierdzenie
-- ---------------------------------------------------------------------------
-- To jest cały sens Outboxa. Wiersz zadania powstaje w tej samej transakcji,
-- co zmiana `payment_status` — więc „zamówienie opłacone bez zakolejkowanego
-- potwierdzenia" jest stanem, którego baza nie dopuszcza.
create or replace function public.kolejkuj_potwierdzenie()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.payment_status = 'opłacone' and old.payment_status is distinct from 'opłacone' then
    perform public.dodaj_zadanie(
      'potwierdzenie_zamowienia',
      'potwierdzenie:' || new.id::text,
      jsonb_build_object('order_id', new.id)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists on_order_paid_queue on public.orders;

create trigger on_order_paid_queue
  after update of payment_status on public.orders
  for each row
  execute function public.kolejkuj_potwierdzenie();

-- ---------------------------------------------------------------------------
-- Sprzątanie
-- ---------------------------------------------------------------------------
-- Zrobione zadania po tygodniu nie niosą już żadnej informacji, a tabela
-- rośnie z każdym zamówieniem. Porażki zostają — są do obejrzenia.
create or replace function public.sprzataj_zadania()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.zadania
  where stan = 'zrobione' and updated_at < now() - interval '7 days';
$$;

revoke all on function public.sprzataj_zadania() from public, anon, authenticated;
