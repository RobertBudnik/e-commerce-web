-- =============================================================================
-- Nordo — schemat bazy
-- Kwoty trzymane w groszach (integer). Żadnych floatów przy pieniądzach.
-- =============================================================================

create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------------
-- Typy
-- ---------------------------------------------------------------------------
create type public.app_role as enum ('owner', 'manager', 'staff', 'customer');

create type public.app_permission as enum (
  'products.read_all',
  'products.write',
  'orders.read_all',
  'orders.write',
  'customers.read',
  'inventory.write',
  'roles.manage'
);

create type public.order_status as enum (
  'nowe', 'w realizacji', 'wysłane', 'dostarczone', 'anulowane'
);

create type public.payment_status as enum (
  'oczekuje', 'opłacone', 'nieudane', 'zwrócone'
);

-- ---------------------------------------------------------------------------
-- Profil i role
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users on delete cascade,
  email text not null,
  full_name text,
  phone text,
  newsletter boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users on delete cascade,
  role public.app_role not null,
  created_at timestamptz not null default now(),
  unique (user_id, role)
);

create table public.role_permissions (
  id bigint generated by default as identity primary key,
  role public.app_role not null,
  permission public.app_permission not null,
  unique (role, permission)
);

create table public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  label text,
  recipient text not null,
  street text not null,
  postal_code text not null,
  city text not null,
  country text not null default 'PL',
  phone text,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create index addresses_user_idx on public.addresses (user_id);

-- ---------------------------------------------------------------------------
-- Katalog
-- ---------------------------------------------------------------------------
create table public.categories (
  id text primary key,
  name text not null,
  description text,
  icon text,
  position integer not null default 0
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  short text,
  description text,
  category_id text references public.categories on delete set null,
  price_cents integer not null check (price_cents >= 0),
  old_price_cents integer check (old_price_cents is null or old_price_cents >= 0),
  currency text not null default 'PLN',
  stock integer not null default 0 check (stock >= 0),
  rating numeric(2, 1) not null default 0 check (rating >= 0 and rating <= 5),
  reviews_count integer not null default 0 check (reviews_count >= 0),
  icon text,
  badge text,
  specs jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index products_category_idx on public.products (category_id);
create index products_active_idx on public.products (is_active) where is_active;

-- Ślad każdej zmiany stanu magazynowego — do rozliczeń i debugowania
create table public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products on delete cascade,
  delta integer not null,
  reason text not null,
  order_id uuid,
  created_by uuid references auth.users on delete set null,
  created_at timestamptz not null default now()
);

create index inventory_product_idx on public.inventory_movements (product_id);

-- ---------------------------------------------------------------------------
-- Ustawienia sklepu — jeden wiersz, edytowalny przez zarządcę
-- ---------------------------------------------------------------------------
create table public.store_settings (
  id boolean primary key default true check (id),
  shipping_flat_cents integer not null default 1999,
  free_shipping_threshold_cents integer not null default 30000,
  currency text not null default 'PLN',
  updated_at timestamptz not null default now()
);

insert into public.store_settings (id) values (true);

-- ---------------------------------------------------------------------------
-- Kupony
-- ---------------------------------------------------------------------------
create table public.coupons (
  code text primary key,
  percent_off integer not null check (percent_off > 0 and percent_off <= 100),
  is_active boolean not null default true,
  valid_from timestamptz,
  valid_to timestamptz,
  max_uses integer,
  used_count integer not null default 0
);

-- ---------------------------------------------------------------------------
-- Zamówienia
-- ---------------------------------------------------------------------------
create sequence public.order_number_seq start 1000;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique
    default 'NOR-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.order_number_seq')::text, 4, '0'),
  user_id uuid references auth.users on delete set null,
  email text not null,
  phone text,
  status public.order_status not null default 'nowe',
  payment_status public.payment_status not null default 'oczekuje',
  subtotal_cents integer not null default 0,
  discount_cents integer not null default 0,
  shipping_cents integer not null default 0,
  total_cents integer not null default 0,
  coupon_code text references public.coupons on delete set null,
  shipping_address jsonb,
  payment_provider text,
  payment_intent_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index orders_user_idx on public.orders (user_id);
create index orders_status_idx on public.orders (status);
create unique index orders_payment_intent_idx
  on public.orders (payment_intent_id) where payment_intent_id is not null;

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders on delete cascade,
  product_id uuid references public.products on delete set null,
  -- Snapshot: nazwa i cena z chwili zakupu, odporne na późniejsze zmiany katalogu
  name text not null,
  unit_price_cents integer not null check (unit_price_cents >= 0),
  qty integer not null check (qty > 0),
  line_total_cents integer not null check (line_total_cents >= 0)
);

create index order_items_order_idx on public.order_items (order_id);

-- ---------------------------------------------------------------------------
-- Lista życzeń
-- ---------------------------------------------------------------------------
create table public.wishlists (
  user_id uuid not null references auth.users on delete cascade,
  product_id uuid not null references public.products on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

-- ---------------------------------------------------------------------------
-- updated_at
-- ---------------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Nowy użytkownik: profil + domyślna rola klienta
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;

  -- Rola nadawana wyłącznie tutaj i przez konto z uprawnieniem roles.manage.
  -- Klient nie może sobie przypisać roli — polityki RLS na user_roles tego pilnują.
  insert into public.user_roles (user_id, role)
  values (new.id, 'customer')
  on conflict (user_id, role) do nothing;

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
