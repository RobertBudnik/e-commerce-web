-- =============================================================================
-- Nordo — historia cen
--
-- Przy obniżce trzeba pokazać najniższą cenę z trzydziestu dni przed promocją.
-- Bez zapisu zmian nie ma z czego jej policzyć, a doliczyć jej wstecz się nie
-- da — dlatego historia zaczyna się dzisiaj, nie wtedy, gdy będzie potrzebna.
--
-- Wpis dokłada wyzwalacz, nie panel. Cenę zmienia się z formularza, z SQL-a
-- i importem; wyzwalacz łapie wszystkie trzy drogi, kod panelu jedną.
--
-- Odczyt publiczny, bo najniższa cena musi być widoczna przy produkcie
-- w sklepie. Zapis: wyłącznie z wyzwalacza — nikt nie dopisuje sobie historii,
-- w której cena była wyższa.
-- =============================================================================

create table if not exists public.historia_cen (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products on delete cascade,
  cena_cents integer not null check (cena_cents >= 0),
  poprzednia_cents integer,
  zmienil uuid references auth.users on delete set null,
  created_at timestamptz not null default now()
);

comment on table public.historia_cen is
  'Zmiany ceny katalogowej. Podstawa najniższej ceny z 30 dni (Omnibus).';

create index if not exists historia_cen_produkt
  on public.historia_cen (product_id, created_at desc);

alter table public.historia_cen enable row level security;

create policy "historia cen: odczyt publiczny" on public.historia_cen
  for select to anon, authenticated
  using (true);

grant select on public.historia_cen to anon, authenticated;

create or replace function public.zapisz_zmiane_ceny()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and new.price_cents is not distinct from old.price_cents then
    return new;
  end if;

  insert into public.historia_cen (product_id, cena_cents, poprzednia_cents, zmienil)
  values (
    new.id,
    new.price_cents,
    case when tg_op = 'UPDATE' then old.price_cents end,
    auth.uid()
  );

  if tg_op = 'UPDATE' then
    perform public.zapisz_w_dzienniku(
      'cena',
      new.slug,
      format('cena: %s → %s gr', old.price_cents, new.price_cents),
      jsonb_build_object('przed', old.price_cents, 'po', new.price_cents)
    );
  end if;

  return new;
end;
$$;

drop trigger if exists products_historia_cen on public.products;
create trigger products_historia_cen
  after insert or update of price_cents on public.products
  for each row execute function public.zapisz_zmiane_ceny();

revoke execute on function public.zapisz_zmiane_ceny()
  from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Najniższa cena z ostatnich 30 dni
--
-- Liczona z historii, nie z `old_price_cents` — tamto pole mówi, co sprzedawca
-- wpisał jako cenę „przed", a nie co faktycznie obowiązywało w sklepie.
-- ---------------------------------------------------------------------------
create or replace function public.najnizsza_cena_30dni(p_produkt uuid)
returns integer
language sql
stable
security invoker
set search_path = public
as $$
  select min(cena_cents)::integer
  from public.historia_cen
  where product_id = p_produkt
    and created_at >= now() - interval '30 days';
$$;

grant execute on function public.najnizsza_cena_30dni(uuid) to anon, authenticated;
