-- =============================================================================
-- Nordo — ślad tego, co dzieje się w sklepie
--
-- Właściciel widzi dziś wyłącznie zamówienia złożone. Nie wie, czego ludzie
-- szukali, co oglądali i co wrzucili do koszyka, zanim zrezygnowali —
-- a to najtańsza informacja o tym, czego w sklepie brakuje.
--
-- Dane zostają u nas: żadnego zewnętrznego licznika, żadnego wysyłania na
-- zewnątrz. Zapisujemy zdarzenie i identyfikator zalogowanego konta, jeśli
-- jest. Bez adresu IP, bez odcisku przeglądarki, bez łączenia w profile.
-- =============================================================================

create type public.shop_event as enum (
  'wejscie_na_produkt',
  'szukanie',
  'dodanie_do_koszyka',
  'usuniecie_z_koszyka',
  'wejscie_do_kasy',
  'zamowienie_zlozone'
);

create table public.shop_events (
  id bigint generated by default as identity primary key,
  event public.shop_event not null,
  -- Produkt, którego dotyczy zdarzenie. On delete set null, bo historia
  -- zachowań ma przetrwać usunięcie pozycji z katalogu.
  product_id uuid references public.products on delete set null,
  -- Fraza wyszukiwania albo inny drobiazg zależny od typu zdarzenia
  detail text,
  qty integer,
  -- Kto, jeśli był zalogowany. Gość zostaje anonimowy i tak ma zostać.
  user_id uuid references auth.users on delete set null,
  created_at timestamptz not null default now()
);

comment on table public.shop_events is
  'Zdarzenia w sklepie do analizy własnej. Bez IP i bez profilowania.';

-- Raporty pytają „co się działo w ostatnich dniach", więc indeks po czasie
create index shop_events_czas on public.shop_events (created_at desc);
create index shop_events_produkt on public.shop_events (product_id, created_at desc)
  where product_id is not null;

alter table public.shop_events enable row level security;

-- Zapis wolno każdemu, także gościowi: inaczej nie policzymy ruchu ludzi,
-- którzy jeszcze się nie zalogowali, a to oni są większością.
create policy "zdarzenia: zapis" on public.shop_events
  for insert to anon, authenticated
  with check (
    -- Można podpisać się wyłącznie sobą albo wcale. Bez tego dowolny gość
    -- dopisywałby zdarzenia w cudzym imieniu.
    user_id is null or user_id = auth.uid()
  );

-- Odczyt wyłącznie dla zaplecza. Zachowania klientów to nie są dane publiczne.
create policy "zdarzenia: odczyt zaplecza" on public.shop_events
  for select to authenticated
  using (public.authorize('orders.read_all'));

grant insert on public.shop_events to anon, authenticated;
grant select on public.shop_events to authenticated;
grant usage, select on sequence public.shop_events_id_seq to anon, authenticated;
