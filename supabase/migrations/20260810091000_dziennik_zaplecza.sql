-- =============================================================================
-- Nordo — dziennik zaplecza
--
-- `inventory_movements` zapisuje, kto ruszył stan magazynowy. Zmiana statusu
-- zamówienia, nadanie przesyłki i zmiana roli nie zostawiają śladu żadnego —
-- a to właśnie o nie pyta się po fakcie, gdy paczka „wyjechała", choć nikt
-- jej nie pakował.
--
-- Tabela jest dopisywalna i nic więcej. Brak polityki `update` i `delete` to
-- nie przeoczenie: wpis, który da się poprawić, przestaje być dowodem i staje
-- się notatnikiem. Z tego samego powodu wiersze dokłada wyłącznie funkcja
-- `security definer`, a nie klient — inaczej podpis pod zmianą byłby wart
-- tyle, ile uczciwość tego, kto go składa.
-- =============================================================================

create table if not exists public.dziennik_zaplecza (
  id bigint generated by default as identity primary key,
  kto uuid references auth.users on delete set null,
  -- Obszar zaplecza: 'zamowienie' | 'przesylka' | 'rola' | 'cena' | 'produkt'
  obszar text not null,
  -- Czytelny identyfikator obiektu: numer zamówienia, slug produktu, e-mail
  obiekt text,
  -- Jedno zdanie po polsku: „stan: nowe → spakowane"
  opis text not null,
  szczegoly jsonb,
  created_at timestamptz not null default now()
);

comment on table public.dziennik_zaplecza is
  'Ślad zmian w zapleczu. Tylko do dopisu — zapisuje wyłącznie zapisz_w_dzienniku().';

create index if not exists dziennik_czas on public.dziennik_zaplecza (created_at desc);
create index if not exists dziennik_obiekt
  on public.dziennik_zaplecza (obszar, obiekt, created_at desc);

alter table public.dziennik_zaplecza enable row level security;

create policy "dziennik: odczyt" on public.dziennik_zaplecza
  for select to authenticated
  using ((select public.authorize('audyt.read')));

grant select on public.dziennik_zaplecza to authenticated;

-- ---------------------------------------------------------------------------
-- Zapis do dziennika
--
-- `authenticated` też traci prawo wykonania. Ta funkcja nie jest do wołania
-- przez API — jest do wołania z wnętrza funkcji, które i tak już zmieniają
-- dane. Gdyby dało się ją zawołać kluczem `anon` albo tokenem klienta, każdy
-- dopisałby do dziennika, co chce.
-- ---------------------------------------------------------------------------
create or replace function public.zapisz_w_dzienniku(
  p_obszar text,
  p_obiekt text,
  p_opis text,
  p_szczegoly jsonb default null
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.dziennik_zaplecza (kto, obszar, obiekt, opis, szczegoly)
  values (auth.uid(), p_obszar, p_obiekt, p_opis, p_szczegoly);
$$;

comment on function public.zapisz_w_dzienniku(text, text, text, jsonb) is
  'Wpis do dziennika zaplecza. Wołana wyłącznie z innych funkcji, nigdy z API.';

revoke execute on function public.zapisz_w_dzienniku(text, text, text, jsonb)
  from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Wpięcie dziennika w operacje, które już istnieją
--
-- Sygnatury zostają nietknięte: `revoke`/`grant` wiszą na sygnaturze, więc
-- dołożenie argumentu utworzyłoby nową funkcję i zostawiło starą z pełnymi
-- prawami. Zmienia się wyłącznie wnętrze.
-- ---------------------------------------------------------------------------
create or replace function public.ustaw_stan_zamowienia(
  p_zamowienie uuid,
  p_stan order_status
)
returns order_status
language plpgsql
security definer
set search_path = public
as $$
declare
  wynik order_status;
  przed order_status;
  numer text;
begin
  if not public.authorize('orders.write') then
    raise exception 'Brak uprawnień do zmiany zamówienia';
  end if;

  -- Wysyłkę nadaje `nadaj_przesylke`, razem z numerem listu. Anulowanie —
  -- `cancel_order`, bo musi zwrócić towar. Zostają dwa stany samej kolejki.
  if p_stan not in ('nowe', 'spakowane') then
    raise exception 'Ta funkcja przestawia wyłącznie „nowe" i „spakowane"';
  end if;

  select status, order_number into przed, numer
  from public.orders where id = p_zamowienie for update;

  if przed is null then
    raise exception 'Nie ma zamówienia o id %', p_zamowienie;
  end if;

  update public.orders set status = p_stan
  where id = p_zamowienie
  returning status into wynik;

  -- Bez zmiany nie ma czego zapisywać: dziennik pełen wierszy „nowe → nowe"
  -- przestaje się nadawać do czytania.
  if przed is distinct from wynik then
    perform public.zapisz_w_dzienniku(
      'zamowienie',
      numer,
      format('stan: %s → %s', przed, wynik),
      jsonb_build_object('przed', przed, 'po', wynik)
    );
  end if;

  return wynik;
end;
$$;

revoke execute on function public.ustaw_stan_zamowienia(uuid, order_status)
  from public, anon, service_role;
grant execute on function public.ustaw_stan_zamowienia(uuid, order_status) to authenticated;

create or replace function public.nadaj_przesylke(
  p_zamowienie uuid,
  p_numer text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  numer text;
  stan public.order_status;
  numer_zamowienia text;
begin
  if not public.authorize('orders.write') then
    raise exception 'Brak uprawnień do zmiany zamówienia';
  end if;

  if coalesce(btrim(p_numer), '') = '' then
    raise exception 'Numer przesyłki jest wymagany';
  end if;

  -- Powtórne nadanie nie nadpisuje numeru: paczka ma jeden list przewozowy,
  -- a drugie dotknięcie przycisku to zwykle ta sama paczka, nie nowa.
  select numer_przesylki, status, order_number
    into numer, stan, numer_zamowienia
  from public.orders where id = p_zamowienie for update;

  if stan is null then
    raise exception 'Nie ma zamówienia o id %', p_zamowienie;
  end if;

  if numer is not null and btrim(numer) <> '' then
    return numer;
  end if;

  if stan = 'anulowane' then
    raise exception 'Zamówienie jest anulowane — towar wrócił na magazyn';
  end if;

  update public.orders
  set numer_przesylki = btrim(p_numer),
      status = 'wysłane'
  where id = p_zamowienie
  returning numer_przesylki into numer;

  perform public.zapisz_w_dzienniku(
    'przesylka',
    numer_zamowienia,
    format('nadano przesyłkę %s', numer),
    jsonb_build_object('numer', numer, 'stan_przed', stan)
  );

  return numer;
end;
$$;

revoke execute on function public.nadaj_przesylke(uuid, text) from public, anon, service_role;
grant execute on function public.nadaj_przesylke(uuid, text) to authenticated;
